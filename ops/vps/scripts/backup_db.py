#!/usr/bin/env python3
from __future__ import annotations

import argparse
import os
import re
import uuid
from datetime import datetime, timezone
from pathlib import Path

from clinic_lifecycle_common import (
    app_root,
    backend_dir,
    backend_env_file,
    fail,
    load_clinic_env,
    parse_database_url,
    pass_message,
    postgres_tool,
    require_env,
    run_command,
)


def _safe_backup_stem(database_name: str) -> str:
    stem = re.sub(r"[^A-Za-z0-9._-]+", "_", database_name.strip())
    stem = stem.strip("._-")
    return stem or "database"


def _reserve_backup_target(backup_file: Path) -> None:
    """BR-010: fail closed BEFORE pg_dump touches the filesystem.

    ``pg_dump -f`` truncates its target, so a silently reused
    ``BACKUP_FILE`` could destroy a previous good archive. Overwriting
    a backup now requires an explicit operator action on the old file,
    never a silent clobber.
    """
    if backup_file.exists():
        fail(
            "Refusing to overwrite an existing backup file: "
            f"{backup_file}. Move or remove the old archive explicitly, "
            "or choose another BACKUP_FILE."
        )


def _next_autogenerated_backup_path(backup_dir: Path, database_name: str) -> Path:
    """BR-010: collision-safe default name.

    The historical ``%Y%m%d_%H%M%S`` precision collided for two calls
    within the same second, and the second dump replaced the first.
    Microsecond precision plus a random token make the default name
    unique in practice; :func:`_reserve_backup_target` still fails
    closed if the path exists.
    """
    timestamp = datetime.now(timezone.utc).strftime("%Y%m%d_%H%M%S_%f")
    token = uuid.uuid4().hex[:8]
    return backup_dir / f"{_safe_backup_stem(database_name)}_{timestamp}_{token}.dump"


def main() -> int:
    parser = argparse.ArgumentParser(description="Create a PostgreSQL backup for a clinic deployment")
    parser.add_argument("--backup-dir", default=os.environ.get("BACKUP_DIR"))
    parser.add_argument("--backup-file", default=os.environ.get("BACKUP_FILE"))
    args = parser.parse_args()

    load_clinic_env()

    database_url = require_env("DATABASE_URL")
    target = parse_database_url(database_url)

    backup_dir = Path(args.backup_dir or (app_root() / "output" / "backups"))
    backup_dir.mkdir(parents=True, exist_ok=True)

    if args.backup_file:
        backup_file = Path(args.backup_file)
        backup_file.parent.mkdir(parents=True, exist_ok=True)
    else:
        backup_file = _next_autogenerated_backup_path(backup_dir, target.name)

    # BR-010: reserve the final name fail-closed for BOTH explicit and
    # autogenerated paths — no silent overwrite of a good archive.
    _reserve_backup_target(backup_file)

    # BR-010: dump into a uniquely reserved private staging file in the
    # SAME directory (same filesystem, atomic publish), validate it,
    # then publish. A failed dump removes the staging file and leaves
    # any existing archive untouched.
    staging_file = backup_file.parent / f".{backup_file.name}.{uuid.uuid4().hex[:8]}.tmp"
    try:
        staging_file.touch(exist_ok=False)  # O_EXCL reservation
    except FileExistsError:
        fail(f"Refusing to reuse a staging path that already exists: {staging_file}")

    cmd = [
        postgres_tool("pg_dump"),
        "-h",
        target.host,
        "-p",
        str(target.port),
        "-U",
        target.user or "postgres",
        "-d",
        target.name,
        "-F",
        "c",
        "-f",
        str(staging_file),
    ]

    env = os.environ.copy()
    env["PGPASSWORD"] = target.password
    try:
        run_command(cmd, env=env, cwd=backend_dir())

        if not staging_file.exists() or staging_file.stat().st_size == 0:
            fail(f"Backup was not created or is empty: {staging_file}")

        os.replace(staging_file, backup_file)  # atomic publish
    except BaseException:
        staging_file.unlink(missing_ok=True)
        raise

    print(f"BACKUP_FILE={backup_file}", flush=True)
    pass_message(f"backup_db created {backup_file}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
