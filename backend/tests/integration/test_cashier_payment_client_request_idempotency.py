def test_replay_returns_stored_result_even_after_visit_fully_settled(
    client, db_session, admin_auth_headers
):
    """A replay must not re-run today's validation.

    After the first keyed payment the rest of the debt is paid with a
    DIFFERENT key, so the visit is fully settled. Replaying the first key
    must still return the original 200 response — not a 400
    "все услуги уже оплачены" and not a new row.
    """
    patient = _make_patient(db_session, phone="+998900550014")
    visit = _make_visit(db_session, patient, 100000)
    first_key = str(uuid4())

    first = client.post(SINGLE_URL, headers=admin_auth_headers, json={
        "visit_id": visit.id, "amount": 40000, "method": "cash",
        "client_request_id": first_key,
    })
    assert first.status_code == 200, first.text
    top_up = client.post(SINGLE_URL, headers=admin_auth_headers, json={
        "visit_id": visit.id, "amount": 60000, "method": "cash",
        "client_request_id": str(uuid4()),
    })
    assert top_up.status_code == 200, top_up.text

    replay = client.post(SINGLE_URL, headers=admin_auth_headers, json={
        "visit_id": visit.id, "amount": 40000, "method": "cash",
        "client_request_id": first_key,
    })
    assert replay.status_code == 200, replay.text
    assert replay.json() == first.json()
    assert len(_paid_rows(db_session, visit)) == 2


def test_grouped_same_client_request_id_replays_without_second_allocation(
    client, db_session, admin_auth_headers
):
    patient = _make_patient(db_session, phone="+998900550015")
    visit_a = _make_visit(db_session, patient, 60000, name="SYNTHETIC-idem-A")
    visit_b = _make_visit(db_session, patient, 40000, name="SYNTHETIC-idem-B")
    key = str(uuid4())
    body = {"visit_ids": [visit_a.id, visit_b.id], "amount": 100000,
            "method": "cash", "client_request_id": key}

    first = client.post(GROUPED_URL, headers=admin_auth_headers, json=body)
    assert first.status_code == 200, first.text
    payload = first.json()
    assert len(payload["payments"]) == 2

    second = client.post(GROUPED_URL, headers=admin_auth_headers, json=body)
    assert second.status_code == 200, second.text
    assert second.json() == payload, "grouped replay must return the stored response"

    db_session.expire_all()
    total_rows = (
        db_session.query(Payment)
        .filter(Payment.visit_id.in_([visit_a.id, visit_b.id]))
        .filter(Payment.status.in_(["paid", "completed"]))
        .count()
    )
    assert total_rows == 2, f"grouped retry must not re-allocate, got {total_rows} rows"


