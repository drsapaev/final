"""CSH-FE-008 remainder (P1 issue 3859): server-side payment idempotency.

Fail-first coverage for the network-loss retry double-charge window on the
two cashier payment creation endpoints. ``POST /api/v1/cashier/payments``
and ``POST /api/v1/cashier/payments/grouped`` accept an optional
``client_request_id`` (UUID) generated by the client once per payment
intent. The server persists the key as a dedup anchor and REPLAYS the
original 200 response for a repeated key instead of creating a second
payment row. Requests without the key keep the legacy behavior.

Contract under test (from the issue):
  (a) same client_request_id twice  -> exactly one payment row, identical
      response body both times;
  (b) different keys                -> separate rows (legitimate partials);
  (c) key absent                    -> legacy behavior (no dedup);
  (d) replay is a stored-result replay: it must NOT re-run today's
      validation (a fully settled visit must still replay the first
      response instead of failing with "already paid");
  (e) a key created by one endpoint must not be replayable by the other;
  (f) the concurrent-duplicate IntegrityError path recovers into a replay
      instead of surfacing 409/500 to the cashier;
  (g) non-UUID keys are rejected by request validation (422);
  (h) RBAC is unchanged (registrar is not allowed to create cashier
      payments, keyed or not).
"""

from decimal import Decimal
from uuid import uuid4

import pytest

from app.models.patient import Patient
from app.models.payment import Payment
from app.models.visit import Visit, VisitService

pytestmark = pytest.mark.integration

SINGLE_URL = "/api/v1/cashier/payments"
GROUPED_URL = "/api/v1/cashier/payments/grouped"


def _make_patient(db_session, *, phone="+998900550011"):
    patient = Patient(first_name="Идем", last_name="Потентный", phone=phone)
    db_session.add(patient)
    db_session.commit()
    return patient


def _make_visit(db_session, patient, amount, *, name="SYNTHETIC-csh-fe-008-idem"):
    visit = Visit(patient_id=patient.id, status="open", discount_mode="none")
    db_session.add(visit)
    db_session.flush()
    db_session.add(
        VisitService(visit_id=visit.id, service_id=1, name=name, qty=1, price=amount)
    )
    db_session.commit()
    return visit


def _paid_rows(db_session, visit):
    return (
        db_session.query(Payment)
        .filter(Payment.visit_id == visit.id)
        .filter(Payment.status.in_(["paid", "completed"]))
        .all()
    )


def test_same_client_request_id_replays_single_payment_without_second_row(
    client, db_session, admin_auth_headers
):
    patient = _make_patient(db_session)
    visit = _make_visit(db_session, patient, 100000)
    key = str(uuid4())
    body = {"visit_id": visit.id, "amount": 40000, "method": "cash",
            "client_request_id": key}

    first = client.post(SINGLE_URL, headers=admin_auth_headers, json=body)
    assert first.status_code == 200, first.text

    second = client.post(SINGLE_URL, headers=admin_auth_headers, json=body)
    assert second.status_code == 200, second.text

    assert first.json() == second.json(), "replay must return the stored response"
    rows = _paid_rows(db_session, visit)
    assert len(rows) == 1, f"retry must not create a second payment row, got {len(rows)}"
    assert rows[0].amount == Decimal("40000")


