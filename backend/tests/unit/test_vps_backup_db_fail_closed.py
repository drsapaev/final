"""Fail-closed backup publication for the VPS ``backup_db.py`` script.

Repairs BR-010 of the backup/restore source review
(``docs/audits/2026-11-05-backup-restore-source-review.md``, PR #3882):

- **BR-010 (P1 candidate):** a caller-supplied ``BACKUP_FILE`` was
  written by ``pg_dump -f`` directly, without an existence check — and
  the autogenerated name had only SECOND-level precision. A reused
  path or two calls within one second could destroy a previous good
  archive: a later failed dump truncates the target before the caller
  learns of the failure.

The fix reserves the final name fail-closed (no silent overwrite),
dumps into a uniquely reserved private staging file in the same
directory, validates it, and publishes atomically with
``os.replace``. The tests import the REAL script; ``run_command`` is
faked at the module boundary (no PostgreSQL required).
"""

from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[3]
OPS_SCRIPTS = REPO_ROOT / "ops" / "vps" / "scripts"


def _load_script():
    if str(OPS_SCRIPTS) not in sys.path:
        sys.path.insert(0, str(OPS_SCRIPTS))
    spec = importlib.util.spec_from_file_location(
        "vps_lifecycle_backup_db", OPS_SCRIPTS / "backup_db.py"
    )
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _patch_postgres_tool(module, monkeypatch):
    """pg_dump need not exist for these behavioral proofs."""

    monkeypatch.setattr(module, "postgres_tool", lambda name: f"/fake/{name}")


class _FrozenDatetime:
    """datetime stand-in frozen at one second — the collision shape."""

    @staticmethod
    def utcnow():
        return _FIXED_NOW

    @classmethod
    def now(cls, tz=None):
        return _FIXED_NOW


_FIXED_NOW = None  # assigned after the real datetime import below


@pytest.fixture()
def backup_env(tmp_path, monkeypatch):
    from datetime import datetime as real_datetime

    global _FIXED_NOW
    _FIXED_NOW = real_datetime(2026, 11, 5, 12, 0, 0)

    app_root = tmp_path / "repo"
    (app_root / "backend").mkdir(parents=True)
    monkeypatch.setenv("APP_ROOT", str(app_root))
    monkeypatch.setenv("DATABASE_URL", "postgresql://user:pw@127.0.0.1:5544/clinicdb")
    backup_dir = tmp_path / "backups"
    backup_dir.mkdir()
    return tmp_path, backup_dir


def _fake_dump_writer(payload: bytes = b"PGDMP-synthetic-archive"):
    """A run_command stand-in that mimics pg_dump -f <path>."""

    from clinic_lifecycle_common import LifecycleError

    def _run(cmd, **kwargs):
        if "-f" not in cmd:
            raise LifecycleError("fake pg_dump: no -f argument")
        Path(cmd[cmd.index("-f") + 1]).write_bytes(payload)

    return _run


def _run_main(module, monkeypatch, args: list[str]):
    monkeypatch.setattr(sys, "argv", ["backup_db.py", *args])
    return module.main()


# ── fail-closed reservation ────────────────────────────────────────────────


def test_existing_backup_file_is_never_overwritten(backup_env, monkeypatch, capsys):
    """An explicit BACKUP_FILE that already exists must be refused.

    Pre-fix RED: pg_dump -f truncated the existing archive silently.
    """

    module = _load_script()
    _patch_postgres_tool(module, monkeypatch)
    _, backup_dir = backup_env
    existing = backup_dir / "clinicdb_good.dump"
    good_bytes = b"PGDMP-previous-good-archive"
    existing.write_bytes(good_bytes)

    calls: list[list[str]] = []
    monkeypatch.setattr(
        module,
        "run_command",
        lambda cmd, **kwargs: calls.append(list(cmd)) or None,
    )

    with pytest.raises(SystemExit) as excinfo:
        _run_main(module, monkeypatch, ["--backup-file", str(existing)])

    captured = capsys.readouterr()
    assert "Refusing to overwrite an existing backup file" in captured.err
    assert existing.read_bytes() == good_bytes, "the good archive must be untouched"
    assert calls == [], "no dump may run against a reserved existing path"
    assert excinfo.value.code != 0


def test_failing_dump_leaves_no_truncated_final_file(backup_env, monkeypatch):
    """A failed dump publishes nothing and cleans its staging file.

    Pre-fix RED: -f pointed at the final name, so the failure left a
    truncated/partial artifact exactly where a good archive belongs.
    """

    module = _load_script()
    _patch_postgres_tool(module, monkeypatch)
    _, backup_dir = backup_env
    target_file = backup_dir / "clinicdb_fresh.dump"

    from clinic_lifecycle_common import LifecycleError

    def _failing_dump(cmd, **kwargs):
        payload = Path(cmd[cmd.index("-f") + 1])
        payload.write_bytes(b"PGDMP-partial-garbage")  # pg_dump truncates first
        raise LifecycleError("pg_dump failed mid-archive")

    monkeypatch.setattr(module, "run_command", _failing_dump)

    with pytest.raises(LifecycleError):
        _run_main(module, monkeypatch, ["--backup-file", str(target_file)])

    assert (
        not target_file.exists()
    ), "BR-010: a failed dump must not leave a partial final archive"
    assert [
        p.name for p in backup_dir.iterdir()
    ] == [], "the private staging file must be cleaned on failure"


def test_same_second_autogenerated_names_do_not_collide(backup_env, monkeypatch):
    """Two backups within one second publish two distinct archives.

    Pre-fix RED (deterministic via the frozen datetime): the second-
    level timestamp reused the same filename, so the second archive
    silently replaced the first.
    """

    module = _load_script()
    _patch_postgres_tool(module, monkeypatch)
    _, backup_dir = backup_env
    monkeypatch.setattr(module, "datetime", _FrozenDatetime)

    published: list[Path] = []
    real_replace = module.os.replace

    def _recording_replace(src, dst):
        published.append(Path(dst))
        real_replace(src, dst)

    monkeypatch.setattr(module.os, "replace", _recording_replace)
    monkeypatch.setattr(module, "run_command", _fake_dump_writer())

    for _ in range(2):
        _run_main(module, monkeypatch, ["--backup-dir", str(backup_dir)])

    assert len(published) == 2, "both invocations must publish an archive"
    assert (
        published[0] != published[1]
    ), "BR-010: same-second invocations collided on one filename"
    assert {p.name for p in backup_dir.iterdir()} == {
        p.name for p in published
    }, "both archives must survive side by side"


# ── atomic publication contract ────────────────────────────────────────────


def test_success_publishes_validated_archive(backup_env, monkeypatch, capsys):
    """Success path: staging validated, published, no leftovers."""

    module = _load_script()
    _patch_postgres_tool(module, monkeypatch)
    tmp_path, backup_dir = backup_env
    target_file = backup_dir / "clinicdb_good.dump"
    payload = b"PGDMP-synthetic-archive"

    monkeypatch.setattr(module, "run_command", _fake_dump_writer(payload))

    _run_main(module, monkeypatch, ["--backup-file", str(target_file)])

    assert target_file.read_bytes() == payload
    assert [p.name for p in backup_dir.iterdir()] == [
        "clinicdb_good.dump"
    ], "the private staging file must be gone after publication"
    captured = capsys.readouterr()
    assert (
        f"BACKUP_FILE={target_file}" in captured.out
    ), "the rehearsal wrapper parses BACKUP_FILE from stdout"
    assert "PASS:" in captured.out


def test_empty_dump_is_never_published(backup_env, monkeypatch, capsys):
    """A zero-byte artifact fails closed before publication."""

    module = _load_script()
    _patch_postgres_tool(module, monkeypatch)
    _, backup_dir = backup_env
    target_file = backup_dir / "clinicdb_empty.dump"

    monkeypatch.setattr(module, "run_command", _fake_dump_writer(b""))

    with pytest.raises(SystemExit):
        _run_main(module, monkeypatch, ["--backup-file", str(target_file)])

    captured = capsys.readouterr()
    assert "Backup was not created or is empty" in captured.err
    assert not target_file.exists(), "an empty artifact must not be published"
    assert [
        p.name for p in backup_dir.iterdir()
    ] == [], "the staging file must be cleaned after the empty-dump failure"


def test_dump_command_contract_unchanged(backup_env, monkeypatch):
    """The pg_dump invocation keeps its custom-format contract."""

    module = _load_script()
    _patch_postgres_tool(module, monkeypatch)
    _, backup_dir = backup_env
    recorded: list[list[str]] = []
    base_writer = _fake_dump_writer()

    def _recording_dump(cmd, **kwargs):
        recorded.append(list(cmd))
        base_writer(cmd, **kwargs)  # produce the artifact so main() succeeds

    monkeypatch.setattr(module, "run_command", _recording_dump)

    _run_main(module, monkeypatch, ["--backup-dir", str(backup_dir)])

    cmd = recorded[0]
    assert Path(cmd[0]).name.startswith("pg_dump")
    assert cmd[cmd.index("-F") + 1] == "c"
    assert cmd[cmd.index("-d") + 1] == "clinicdb"
